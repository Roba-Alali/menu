export function getStarterBundle(slug: string): RestaurantBundle | null {
  const dataset = getStarterSeedDataset();
  const restaurant = dataset.restaurants.find((r) => r.slug === slug);
  if (!restaurant) return null;
  return {
    restaurant,
    branches: dataset.branches.filter((b) => b.restaurantId === restaurant.id),
    categories: dataset.categories
      .filter((c) => c.restaurantId === restaurant.id)
      .sort((a, b) => a.sortOrder - b.sortOrder),
    products: dataset.products
      .filter((p) => p.restaurantId === restaurant.id)
      .sort((a, b) => a.sortOrder - b.sortOrder),
    domains: dataset.domains.filter((d) => d.restaurantId === restaurant.id),
    qrCodes: dataset.qrCodes.filter((q) => q.restaurantId === restaurant.id),
    members: dataset.members.filter((m) => m.restaurantId === restaurant.id),
    orders: dataset.orders.filter((o) => o.restaurantId === restaurant.id),
  };
}
